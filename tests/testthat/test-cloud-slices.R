test_that("cloud waveform slices read only the requested contiguous range", {
  skip_if_not_installed("reticulate")
  skip_if_not(reticulate::py_module_available("numpy"))
  reticulate::py_run_string("import numpy as np\nclass SliceProbe:\n    shape = (100,)\n    chunks = None\n    dtype = np.dtype('float64')\n    requested = None\n    def __getitem__(self, key):\n        self.requested = key\n        return np.arange(1, 101, dtype=float)[key]\nprobe = SliceProbe()")
  probe <- reticulate::py_eval("probe", convert = FALSE)
  dataset <- getFromNamespace("GEDICloudDataset", "rGEDI")$new(probe)
  expect_equal(as.numeric(dataset[10:20]), 10:20)
  expect_null(dim(dataset[10:20]))
  expect_identical(reticulate::py_eval("isinstance(probe.requested, slice)"), TRUE)
  expect_equal(reticulate::py_eval("probe.requested.start"), 9)
  expect_equal(reticulate::py_eval("probe.requested.stop"), 20)
  expect_equal(as.numeric(dataset[bit64::as.integer64(10:20)]), 10:20)
  expect_equal(as.numeric(dataset[100]), 100)
  expect_equal(as.numeric(dataset[c(8, 2)]), c(8, 2))
  expect_equal(as.numeric(dataset[]), 1:100)
})


test_that("cloud waveform extraction handles unsigned 64-bit sample addresses", {
  skip_if_not_installed("reticulate")
  skip_if_not(reticulate::py_module_available("h5py"))
  skip_if_not(reticulate::py_module_available("numpy"))
  np <- reticulate::import("numpy", convert = FALSE)
  h5py <- reticulate::import("h5py", convert = FALSE)
  filename <- tempfile(fileext = ".h5")
  h5 <- h5py$File(filename, "w")
  on.exit(try(h5$close(), silent = TRUE), add = TRUE)
  g <- h5$create_group("BEAM0110")
  shot <- "40920600200410567"
  g$create_dataset("shot_number", data = np$array(list(shot), dtype = "uint64"))
  g$create_dataset("rx_sample_start_index", data = np$array(list(1L), dtype = "uint64"))
  g$create_dataset("rx_sample_count", data = np$array(list(3L), dtype = "uint16"))
  g$create_dataset("rxwaveform", data = np$array(c(10, 25, 15)))
  geo <- g$create_group("geolocation")
  geo$create_dataset("elevation_bin0", data = np$array(list(12)))
  geo$create_dataset("elevation_lastbin", data = np$array(list(9)))
  cloud <- getFromNamespace("GEDICloudH5", "rGEDI")$new(h5)
  result <- getLevel1BWF(readLevel1B(cloud), shot)
  expect_equal(as.numeric(result@dt$rxwaveform), c(10, 25, 15))
  expect_equal(nrow(result@dt), 3L)
  expect_null(dim(result@dt$rxwaveform))
  expect_true(all(is.finite(result@dt$elevation)))
})

